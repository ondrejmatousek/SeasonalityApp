const assert=require('node:assert/strict');
const {analyze,summarize}=require('../wwwroot/js/cot-analogs.js');
const day=86400000,iso=t=>new Date(t).toISOString().slice(0,10),start=Date.parse('2020-01-07T00:00:00Z');
const reports=Array.from({length:40},(_,i)=>({date:iso(start+i*7*day),commercial:{index:i===39?95:90},nonCommercial:{index:10}}));
const prices=Array.from({length:340},(_,i)=>({date:iso(start+i*day),close:100+i}));
const opts={group:'commercial',mode:'latest',tolerance:10,asOf:'2020-12-31'};
const result=analyze(reports,prices,opts);
assert.deepEqual(result.range,[85,100]);
assert.ok(result.samples.length>2&&result.samples.length<reports.length);
assert.equal(result.samples[0].entryDate,'2020-01-14','Never enter on position date');
assert.ok(Math.abs(result.samples[0].outcomes[2].returnPct-(121/107-1)*100)<1e-9);
for(let i=1;i<result.samples.length;i++)assert.ok(result.samples[i].entryDate>result.samples[i-1].outcomes[8].date,'Windows must not overlap');
for(const h of result.horizons)assert.equal(h.count,result.samples.length,'Use same completed sample for all horizons');
assert.deepEqual(analyze(reports,prices,{...opts,mode:'low'}).samples,[]);
assert.deepEqual(analyze(reports,prices,{...opts,group:'nonReportable'}).samples,[]);
assert.equal(analyze(reports,prices,{...opts,asOf:'2020-02-01'}).samples.length,0,'Incomplete 8-week window excluded');
const missing=prices.filter(r=>r.date<'2020-01-25'||r.date>'2020-02-15');
assert.ok(!analyze(reports,missing,opts).samples.some(s=>s.reportDate==='2020-01-07'),'Missing prices excluded');
const bad=prices.map(r=>r.date==='2020-01-20'?{...r,close:NaN}:r);
assert.ok(!analyze(reports,bad,opts).samples.some(s=>s.reportDate==='2020-01-07'),'Invalid internal price excluded');
assert.deepEqual(summarize([-10,0,10,20]),{count:4,mean:5,median:5,q25:-2.5,q75:12.5,min:-10,max:20,positive:50});
assert.equal(summarize([]).median,null);
assert.throws(()=>analyze(reports,prices,{...opts,tolerance:-1}));
console.log('COT analog checks passed: delayed entry, no future outcomes, non-overlapping samples, gaps, missing index, percentiles.');
